// Builds the vendored virtual shell that ships inside @nanocodana/core.
//
// WHY THIS EXISTS
//
// just-bash is the virtual shell behind core's Bash tool. Depending on it
// normally has two costs we don't want to pass to consumers:
//
//   1. It doesn't load on runtimes without a Node polyfill layer. Its browser
//      bundle statically imports node:zlib, so workerd refuses to start the
//      Worker and strict bundlers refuse to resolve it. Consumers would each
//      have to configure a bundler alias — per bundler, forever.
//   2. It brings ~70 MB and ~70 packages of transitive dependencies (a compiled
//      CPython, SQLite as wasm, a JS interpreter, RE2) to serve commands that
//      the browser build cannot run anyway.
//
// So we bundle just-bash's own published browser artifact once, at *our* build
// time, aliasing node:zlib to a stub. The result is a single self-contained file
// with zero `node:` imports and zero runtime dependencies. just-bash becomes a
// devDependency and disappears from consumers' trees entirely.
//
// This is deliberately built from the PUBLISHED npm artifact, not from their
// source: no repo clone, no pnpm, no git-lfs, no toolchain of theirs to keep
// working. `npm install` pins the input, so the output is reproducible.
//
// WHAT IS LOST: gzip, gunzip, zcat, and `rg -z` throw instead of running. They
// were already unavailable to core's shell on any runtime without node:zlib, and
// @nanocodana/nodejs is unaffected — it uses the real just-bash directly.
import { build } from 'esbuild'
import { copyFile, mkdir, readFile } from 'node:fs/promises'
import { existsSync, readFileSync } from 'node:fs'
import { dirname, join, parse } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = join(here, '..')
const outDir = join(pkgRoot, 'dist', 'shell')

// `import.meta.resolve`, not `require.resolve`: just-bash's exports map defines
// "./browser" with an `import` condition only, so CJS resolution can't see it.
const entry = fileURLToPath(import.meta.resolve('just-bash/browser'))

// The exports map also doesn't expose ./package.json, so find the package root
// by walking up from the entry point rather than requiring the manifest.
function packageRootOf(startFile, name) {
  let dir = dirname(startFile)
  const { root } = parse(dir)
  while (true) {
    const manifest = join(dir, 'package.json')
    if (existsSync(manifest)) {
      const pkg = JSON.parse(readFileSync(manifest, 'utf8'))
      if (pkg.name === name) return { dir, pkg }
    }
    if (dir === root) throw new Error(`Could not locate the ${name} package root`)
    dir = dirname(dir)
  }
}

const { dir: shellPkgDir, pkg: shellPkg } = packageRootOf(entry, 'just-bash')
const version = shellPkg.version

await mkdir(outDir, { recursive: true })

const result = await build({
  entryPoints: [entry],
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  outfile: join(outDir, 'bundle.js'),
  alias: { 'node:zlib': join(here, 'shims', 'zlib-unavailable.js') },
  legalComments: 'none',
  metafile: true,
  banner: {
    js:
      `// @nanocodana/core — vendored virtual shell, built from just-bash@${version}\n` +
      `// (https://github.com/vercel-labs/just-bash), Apache-2.0. See LICENSE.just-bash.\n` +
      `// Generated by build/bundle-shell.mjs — do not edit.`,
  },
})

// The whole point of this build is a shell with no Node dependency. If a `node:`
// import survives, the artifact is broken on workerd and in strict bundlers —
// fail here rather than shipping it.
const code = await readFile(join(outDir, 'bundle.js'), 'utf8')
const nodeImports = [...code.matchAll(/from\s*["'](node:[a-z_/]+)["']/g)].map(m => m[1])
if (nodeImports.length > 0) {
  throw new Error(
    `Vendored shell contains ${nodeImports.length} node: import(s): ` +
      `${[...new Set(nodeImports)].join(', ')}. ` +
      `Add an alias in this script, or the bundle will not load on workerd.`,
  )
}

// Apache-2.0 requires the license to travel with redistributed builds.
await copyFile(join(shellPkgDir, 'LICENSE'), join(outDir, 'LICENSE.just-bash'))

// tsc resolves `import('./shell/bundle.js')` through src/shell/bundle.d.ts, but
// does not copy .d.ts inputs to outDir — consumers need one next to the bundle.
await copyFile(join(pkgRoot, 'src', 'shell', 'bundle.d.ts'), join(outDir, 'bundle.d.ts'))

const bytes = Buffer.byteLength(code)
const inputs = Object.keys(result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].inputs).length
console.log(
  `  shell: ${(bytes / 1024 / 1024).toFixed(2)} MB from just-bash@${version} ` +
    `(${inputs} modules, 0 node: imports)`,
)
