// Vendors the virtual shell into @nanocodana/nodejs.
//
// Unlike core's build, this bundles just-bash's **Node** entry point, keeping
// node:fs/path/dns and the full command set — sqlite3, tar, real gzip, and the
// node:fs-backed filesystems. That's the point of this adapter, so nothing is
// stubbed here.
//
// WHY VENDOR AT ALL
//
// just-bash brings ~70 MB and ~150 transitive packages, the bulk of which are
// pure JavaScript that a bundler can inline for free (papaparse, yaml, re2js,
// modern-tar, turndown, …). Bundling them once at our build time takes the
// adapter's install from ~135 MB to roughly half that, and drops just-bash out
// of consumers' dependency trees entirely.
//
// WHAT STAYS A REAL DEPENDENCY
//
//   quickjs-emscripten   wasm engine behind js-exec, resolved dynamically
//   @mongodb-js/zstd     native .node addon
//   node-liblzma         native .node addon
//
// sql.js is deliberately NOT among them: it installs 18 MB to deliver 45 kB of
// glue and a 644 kB .wasm — the rest is asm.js and debug builds for pre-wasm
// environments, shipped to everyone because the package has no `files` field.
// The glue is inlined into the sqlite3 worker below and only the .wasm ships.
//
// THE LAYOUT IS LOAD-BEARING
//
//   sqlite3 looks for   <dir>/sqlite3-worker.js        → workers sit BESIDE the bundle
//   python3's worker    <dir>/../../../vendor/         → that dir must be 3 below vendor/
//
// Hence dist/shell/lib/ for the bundle and workers, with vendor/ at the package
// root. Verified by packages/cli/shell.test.mjs — flat loses python3, a chunks/
// subdirectory loses sqlite3.
import { build } from 'esbuild'
import { cp, mkdir, readFile, rm } from 'node:fs/promises'
import { existsSync, readFileSync } from 'node:fs'
import { dirname, join, parse } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = join(here, '..')
const outDir = join(pkgRoot, 'dist', 'shell', 'lib')
const vendorDir = join(pkgRoot, 'vendor')

const EXTERNAL = ['quickjs-emscripten', '@mongodb-js/zstd', 'node-liblzma']
const WORKERS = ['worker.js', 'js-exec-worker.js']
const BUNDLED_WORKERS = [
  { worker: 'sqlite3-worker.js', assets: [['sql.js', 'dist/sql-wasm.wasm']] },
]

// sql.js locates its .wasm via __dirname, which does not exist in ESM.
const CJS_GLOBALS_BANNER =
  "import{createRequire as __cr}from'node:module';" +
  "import{fileURLToPath as __f}from'node:url';" +
  "import{dirname as __d}from'node:path';" +
  'const require=__cr(import.meta.url);' +
  'const __filename=__f(import.meta.url);' +
  'const __dirname=__d(__filename);'

function packageRootOf(startFile, name) {
  let dir = dirname(startFile)
  const { root } = parse(dir)
  while (true) {
    const manifest = join(dir, 'package.json')
    if (existsSync(manifest)) {
      const pkg = JSON.parse(readFileSync(manifest, 'utf8'))
      if (pkg.name === name) return { dir, pkg }
    }
    if (dir === root) throw new Error(`Could not locate the ${name} package root`)
    dir = dirname(dir)
  }
}

const entry = fileURLToPath(import.meta.resolve('just-bash'))
const { dir: shellPkgDir, pkg: shellPkg } = packageRootOf(entry, 'just-bash')

await rm(outDir, { recursive: true, force: true })
await rm(vendorDir, { recursive: true, force: true })
await mkdir(outDir, { recursive: true })

await build({
  entryPoints: [entry],
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  outfile: join(outDir, 'bundle.js'),
  external: EXTERNAL,
  legalComments: 'none',
  banner: {
    js:
      `// @nanocodana/nodejs — vendored shell, built from just-bash@${shellPkg.version}\n` +
      `// (https://github.com/vercel-labs/just-bash), Apache-2.0. See LICENSE.just-bash.\n` +
      `// Generated by build/bundle-shell.mjs — do not edit.\n` +
      CJS_GLOBALS_BANNER,
  },
})

for (const worker of WORKERS) {
  await cp(join(shellPkgDir, 'dist', 'bundle', 'chunks', worker), join(outDir, worker))
}

for (const { worker, assets } of BUNDLED_WORKERS) {
  await build({
    entryPoints: [join(shellPkgDir, 'dist', 'bundle', 'chunks', worker)],
    bundle: true,
    minify: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    outfile: join(outDir, worker),
    external: EXTERNAL,
    legalComments: 'none',
    banner: { js: CJS_GLOBALS_BANNER },
  })
  for (const [pkg, assetPath] of assets) {
    const { dir } = packageRootOf(fileURLToPath(import.meta.resolve(pkg)), pkg)
    await cp(join(dir, ...assetPath.split('/')), join(outDir, assetPath.split('/').pop()))
  }
}

// CPython, for the opt-in python3 command. Gitignored, shipped via `files`.
await cp(join(shellPkgDir, 'vendor'), vendorDir, { recursive: true })

await cp(join(shellPkgDir, 'LICENSE'), join(outDir, 'LICENSE.just-bash'))
await cp(join(pkgRoot, 'src', 'shell', 'lib', 'bundle.d.ts'), join(outDir, 'bundle.d.ts'))

const bytes = (await readFile(join(outDir, 'bundle.js'))).byteLength
console.log(`  shell: ${(bytes / 1024 / 1024).toFixed(2)} MB from just-bash@${shellPkg.version}`)
